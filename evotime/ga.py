"""
ga.py — Pure Hand-written Genetic Algorithm Engine for EvoTime.

This module implements a Genetic Algorithm from scratch in pure Python without
third-party optimization packages (no DEAP, PyGAD, or SciPy).

Core GA Cycle:
1. Initialization: Creates `population_size` randomized timetables from raw specifications.
   Optionally biases placement toward faculty-available slots, then applies structural repair.
2. Fitness Evaluation: Scores every timetable via `fitness.evaluate()`. The goal is to
   MINIMIZE penalty = (1000 * hard_violations) + (10 * soft_violations).
3. Elitism: Directly preserves the top `elitism_count` best candidate timetables into the
   next generation, guaranteeing the best penalty never gets worse.
4. Tournament Selection: Randomly selects `k` candidates from the population and chooses
   the winner (lowest penalty) to be a parent.
5. Crossover: Uniform crossover by `lecture_id`. For each lecture, the child inherits its
   (room, day, start_period) from either Parent A or Parent B with 50% probability.
6. Mutation: Includes random gene reassignment, slot swapping, and conflict-directed
   mutation (prioritizing genes involved in clashes).
7. Repair: Applies `repair.repair_timetable()` after crossover and mutation to ensure
   structural bounds and room kinds remain valid.
8. Termination: Stops when hard violations reach 0 and penalty <= threshold, or when
   max_generations is reached.
9. Validation: The final best timetable is independently evaluated by `validator.validate()`.
   Status is SUCCESS only if the validator confirms 0 hard violations.
"""

import copy
import random
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Set, Tuple

from evotime.config import (
    DEFAULT_CROSSOVER_RATE,
    DEFAULT_ELITISM_COUNT,
    DEFAULT_MAX_GENERATIONS,
    DEFAULT_MUTATION_RATE,
    DEFAULT_POPULATION_SIZE,
    DEFAULT_RANDOM_SEED,
    DEFAULT_TOURNAMENT_K,
    GAConfig,
    NUM_DAYS,
    PERIODS_PER_DAY,
)
from evotime.fitness import FitnessBreakdown, evaluate
from evotime.models import Gene, Lecture, Room, Timetable
from evotime.repair import repair_timetable
from evotime.validator import ValidationReport, validate


@dataclass
class GAResult:
    """
    Complete results and audit telemetry produced by a Genetic Algorithm run.

    Attributes:
        dataset_name: Name of the college dataset used.
        status: "SUCCESS" if independent validator confirms 0 hard violations, else "FAILED".
        generations_run: Total generations executed.
        stop_reason: Explanation of why the run terminated.
        initial_best: The best candidate timetable from Generation 0.
        final_best: The optimal candidate timetable found across all generations.
        initial_breakdown: Detailed penalty evaluation of the initial best timetable.
        final_breakdown: Detailed penalty evaluation of the final best timetable.
        validation_report: Report generated by the independent validator on final_best.
        history: Generation-by-generation telemetry (best penalty, avg penalty, hard, soft).
    """
    dataset_name: str
    status: str
    generations_run: int
    stop_reason: str
    initial_best: Timetable
    final_best: Timetable
    initial_breakdown: FitnessBreakdown
    final_breakdown: FitnessBreakdown
    validation_report: ValidationReport
    history: List[Dict[str, Any]] = field(default_factory=list)


# ============================================================================
# Population Initialization (Randomized + Feasibility Bias)
# ============================================================================

def init_population(
    dataset: Any,
    pop_size: int,
    rng: random.Random,
    bias_available_slots: bool = True,
) -> List[Timetable]:
    """
    Initializes a population of candidate Timetables using purely random assignments.

    Args:
        dataset: The college dataset with lectures, rooms, batches, teachers.
        pop_size: Number of individual timetables in the population.
        rng: Seeded random.Random instance for reproducibility.
        bias_available_slots: If True, biases 70% of initial placements toward slots
                              where the assigned teacher is available.

    Returns:
        List of initialized, structurally repaired Timetables.
    """
    population: List[Timetable] = []
    classrooms = [r.id for r in dataset.rooms.values() if r.kind == "classroom"]
    labs = [r.id for r in dataset.rooms.values() if r.kind == "lab"]

    for _ in range(pop_size):
        genes: List[Gene] = []
        # Group lectures by (batch_id, subject_id) for theory distinct-day assignment
        batch_sub_lectures: Dict[Tuple[str, str], List[Lecture]] = {}
        for lec in dataset.lectures:
            sub = dataset.subjects.get(lec.subject_id)
            if sub and sub.type == "theory":
                batch_sub_lectures.setdefault((lec.batch_id, lec.subject_id), []).append(lec)

        # Pre-assign distinct random days for each theory (batch, subject) group
        assigned_days_by_lec: Dict[str, int] = {}
        for (b_id, s_id), lecs in batch_sub_lectures.items():
            num_sessions = len(lecs)
            if num_sessions <= NUM_DAYS:
                chosen_days = rng.sample(range(NUM_DAYS), num_sessions)
            else:
                chosen_days = [rng.randint(0, NUM_DAYS - 1) for _ in range(num_sessions)]
            for lec_obj, d in zip(lecs, chosen_days):
                assigned_days_by_lec[lec_obj.lecture_id] = d

        for lec in dataset.lectures:
            room_pool = labs if lec.needs_lab else classrooms
            room_id = rng.choice(room_pool) if room_pool else rng.choice(list(dataset.rooms.keys()))

            max_start = PERIODS_PER_DAY - lec.duration
            if lec.lecture_id in assigned_days_by_lec:
                day = assigned_days_by_lec[lec.lecture_id]
            else:
                day = rng.randint(0, NUM_DAYS - 1)

            start_p = rng.randint(0, max_start)

            # Optional bias: try placing within teacher's available slots on the assigned day
            if bias_available_slots and rng.random() < 0.70:
                teacher = dataset.teachers.get(lec.teacher_id)
                if teacher and teacher.available_slots:
                    valid_avail = [
                        (d, p) for (d, p) in teacher.available_slots
                        if d == day and p <= max_start and all((d, p + i) in teacher.available_slots for i in range(lec.duration))
                    ]
                    if valid_avail:
                        day, start_p = rng.choice(valid_avail)

            genes.append(Gene(lecture_id=lec.lecture_id, room_id=room_id, day=day, start_period=start_p))

        ind = Timetable(genes=genes)
        repair_timetable(ind, dataset, rng)
        population.append(ind)

    return population


# ============================================================================
# Genetic Operators: Selection, Crossover, Mutation
# ============================================================================

def tournament_selection(
    population: List[Timetable],
    penalties: List[float],
    k: int,
    rng: random.Random,
) -> Timetable:
    """
    Tournament selection (k candidates):
    Picks k random individuals from the population and returns a copy of the best (lowest penalty).
    """
    selected_indices = rng.sample(range(len(population)), k)
    best_idx = min(selected_indices, key=lambda idx: penalties[idx])
    return copy.deepcopy(population[best_idx])


def crossover(
    parent_a: Timetable,
    parent_b: Timetable,
    crossover_rate: float,
    rng: random.Random,
    dataset: Optional[Any] = None,
) -> Timetable:
    """
    Group Crossover by (batch, subject):
    Inherits all sessions of a given (batch, subject) group from ONE parent per group
    with 50% probability, rather than choosing per individual lecture.

    Why this keeps distinct days intact:
    If both Parent A and Parent B satisfy the rule that every theory subject appears at
    most once per day, inheriting the entire group of sessions from Parent A or Parent B
    guarantees that the child preserves the distinct-day property without recombining
    lectures onto duplicate days.
    """
    if rng.random() > crossover_rate:
        return copy.deepcopy(parent_a)

    # Determine group key for each gene
    lec_map = {l.lecture_id: l for l in dataset.lectures} if dataset else {}

    # Map group_key -> bool (True for Parent A, False for Parent B)
    group_choices: Dict[Any, bool] = {}

    child_genes: List[Gene] = []
    for g_a, g_b in zip(parent_a.genes, parent_b.genes):
        lec = lec_map.get(g_a.lecture_id)
        if lec:
            group_key = (lec.batch_id, lec.subject_id)
        else:
            # Fallback to prefix before session index in lecture_id
            group_key = g_a.lecture_id.rsplit("_", 1)[0] if "_" in g_a.lecture_id else g_a.lecture_id

        if group_key not in group_choices:
            group_choices[group_key] = (rng.random() < 0.5)

        source = g_a if group_choices[group_key] else g_b
        child_genes.append(
            Gene(
                lecture_id=source.lecture_id,
                room_id=source.room_id,
                day=source.day,
                start_period=source.start_period,
            )
        )

    return Timetable(genes=child_genes)


def _get_clashing_gene_indices(timetable: Timetable, dataset: Any) -> Set[int]:
    """Helper to detect gene indices involved in clashes, unavailability, or same-day theory duplicates."""
    lecture_map: Dict[str, Lecture] = {l.lecture_id: l for l in dataset.lectures}
    slot_teachers: Dict[Tuple[str, int, int], List[int]] = {}
    slot_rooms: Dict[Tuple[str, int, int], List[int]] = {}
    slot_batches: Dict[Tuple[str, int, int], List[int]] = {}
    slot_theory_dups: Dict[Tuple[str, int, str], List[int]] = {}
    clashing_indices: Set[int] = set()

    for idx, gene in enumerate(timetable.genes):
        lec = lecture_map.get(gene.lecture_id)
        if not lec:
            continue
        teacher = dataset.teachers.get(lec.teacher_id)
        sub = dataset.subjects.get(lec.subject_id)

        if sub and sub.type == "theory" and 0 <= gene.day < NUM_DAYS:
            dup_key = (lec.batch_id, gene.day, lec.subject_id)
            slot_theory_dups.setdefault(dup_key, []).append(idx)

        for p in range(lec.duration):
            period = gene.start_period + p
            if 0 <= gene.day < NUM_DAYS and 0 <= period < PERIODS_PER_DAY:
                slot = (gene.day, period)
                if teacher and slot not in teacher.available_slots:
                    clashing_indices.add(idx)

                t_key = (lec.teacher_id, gene.day, period)
                slot_teachers.setdefault(t_key, []).append(idx)

                r_key = (gene.room_id, gene.day, period)
                slot_rooms.setdefault(r_key, []).append(idx)

                b_key = (lec.batch_id, gene.day, period)
                slot_batches.setdefault(b_key, []).append(idx)

    all_groups = (
        list(slot_teachers.values())
        + list(slot_rooms.values())
        + list(slot_batches.values())
        + list(slot_theory_dups.values())
    )
    for group in all_groups:
        if len(group) > 1:
            clashing_indices.update(group)

    return clashing_indices


def mutate(
    timetable: Timetable,
    dataset: Any,
    mutation_rate: float,
    rng: random.Random,
) -> None:
    """
    Mutates genes in-place:
    - Type 1: Reassign to a new random room.
    - Type 2: Move to a new random day and start period.
    - Type 3: Swap time slots with another gene of the same duration.
    - Conflict-directed mutation: Identifies clashing genes and nudges them into new slots.
    """
    lecture_map: Dict[str, Lecture] = {l.lecture_id: l for l in dataset.lectures}
    classrooms = [r.id for r in dataset.rooms.values() if r.kind == "classroom"]
    labs = [r.id for r in dataset.rooms.values() if r.kind == "lab"]

    # 1. Conflict-directed mutation: prioritize clashing genes
    clashing_indices = _get_clashing_gene_indices(timetable, dataset)
    if clashing_indices and rng.random() < 0.65:
        target_idx = rng.choice(list(clashing_indices))
        gene = timetable.genes[target_idx]
        lec = lecture_map.get(gene.lecture_id)
        if lec:
            sub = dataset.subjects.get(lec.subject_id)
            teacher = dataset.teachers.get(lec.teacher_id)
            room_pool = labs if lec.needs_lab else classrooms
            max_start = PERIODS_PER_DAY - lec.duration

            # Check if this gene is part of a same-day theory duplicate
            is_theory = (sub is not None and sub.type == "theory")
            same_day_days = set()
            if is_theory:
                same_day_days = {
                    other_g.day for i, other_g in enumerate(timetable.genes)
                    if i != target_idx
                    and lecture_map.get(other_g.lecture_id)
                    and lecture_map[other_g.lecture_id].batch_id == lec.batch_id
                    and lecture_map[other_g.lecture_id].subject_id == lec.subject_id
                    and 0 <= other_g.day < NUM_DAYS
                }

            allowed_days = [d for d in range(NUM_DAYS) if d not in same_day_days] if same_day_days else list(range(NUM_DAYS))
            if not allowed_days:
                allowed_days = list(range(NUM_DAYS))

            # Build occupancy of other genes to prefer free slots
            occupied_batch = set()
            occupied_teacher = set()
            occupied_rooms = set()
            for i, other_g in enumerate(timetable.genes):
                if i == target_idx:
                    continue
                o_lec = lecture_map.get(other_g.lecture_id)
                if not o_lec or other_g.day not in allowed_days:
                    continue
                for p in range(o_lec.duration):
                    slot = (other_g.day, other_g.start_period + p)
                    if o_lec.batch_id == lec.batch_id:
                        occupied_batch.add(slot)
                    if o_lec.teacher_id == lec.teacher_id:
                        occupied_teacher.add(slot)
                    occupied_rooms.add((other_g.room_id, slot[0], slot[1]))

            # Find candidate (day, start_period, room) that are free
            ideal_candidates = []
            for d in allowed_days:
                for p in range(max_start + 1):
                    slots = [(d, p + offset) for offset in range(lec.duration)]
                    if teacher and not all(s in teacher.available_slots for s in slots):
                        continue
                    if any(s in occupied_batch or s in occupied_teacher for s in slots):
                        continue
                    # Check room availability
                    for r_id in room_pool:
                        if not any((r_id, s[0], s[1]) in occupied_rooms for s in slots):
                            ideal_candidates.append((d, p, r_id))

            if ideal_candidates:
                d_choice, p_choice, r_choice = rng.choice(ideal_candidates)
                gene.day = d_choice
                gene.start_period = p_choice
                gene.room_id = r_choice
            else:
                gene.day = rng.choice(allowed_days)
                gene.start_period = rng.randint(0, max_start)
                if room_pool:
                    gene.room_id = rng.choice(room_pool)

    # 2. Standard uniform per-gene mutation
    for idx, gene in enumerate(timetable.genes):
        if rng.random() < mutation_rate:
            lec = lecture_map.get(gene.lecture_id)
            if not lec:
                continue

            mutation_type = rng.choice(["time", "room", "swap"])
            max_start = PERIODS_PER_DAY - lec.duration

            if mutation_type == "time":
                gene.day = rng.randint(0, NUM_DAYS - 1)
                gene.start_period = rng.randint(0, max_start)
            elif mutation_type == "room":
                room_pool = labs if lec.needs_lab else classrooms
                if room_pool:
                    gene.room_id = rng.choice(room_pool)
            elif mutation_type == "swap":
                # Find another gene with matching duration to swap slots
                candidates = [
                    other_idx for other_idx, other_g in enumerate(timetable.genes)
                    if other_idx != idx and lecture_map[other_g.lecture_id].duration == lec.duration
                ]
                if candidates:
                    other_idx = rng.choice(candidates)
                    other_g = timetable.genes[other_idx]
                    gene.day, other_g.day = other_g.day, gene.day
                    gene.start_period, other_g.start_period = other_g.start_period, gene.start_period


# ============================================================================
# Main Genetic Algorithm Optimization Loop
# ============================================================================

def run_ga(
    dataset: Any,
    config: Optional[GAConfig] = None,
    callback: Optional[Callable[[int, FitnessBreakdown, float], None]] = None,
) -> GAResult:
    """
    Executes the full Genetic Algorithm optimization workflow.

    Args:
        dataset: The TimetableDataset to solve.
        config: Optional GAConfig parameters (falls back to defaults).
        callback: Optional callback(generation, best_breakdown, avg_penalty) invoked each generation.

    Returns:
        GAResult bundle containing the evolved timetable, history, and independent validation.
    """
    if config is None:
        config = GAConfig()

    rng = random.Random(config.seed)

    # 1. Initialize population
    population = init_population(dataset, config.population_size, rng)

    # Evaluate Generation 0
    breakdowns = [evaluate(ind, dataset, config) for ind in population]
    penalties = [b.penalty for b in breakdowns]

    best_idx = min(range(len(population)), key=lambda i: penalties[i])
    initial_best = copy.deepcopy(population[best_idx])
    initial_breakdown = copy.deepcopy(breakdowns[best_idx])

    current_best_ind = copy.deepcopy(initial_best)
    current_best_breakdown = copy.deepcopy(initial_breakdown)

    history: List[Dict[str, Any]] = []
    stop_reason = f"Reached maximum generations limit ({config.max_generations})"

    for gen in range(1, config.max_generations + 1):
        # Elitism: preserve top E individuals
        ranked_indices = sorted(range(len(population)), key=lambda i: penalties[i])
        new_population: List[Timetable] = [
            copy.deepcopy(population[idx]) for idx in ranked_indices[: config.elitism_count]
        ]

        # Generate children to fill population
        while len(new_population) < config.population_size:
            parent_a = tournament_selection(population, penalties, config.tournament_k, rng)
            parent_b = tournament_selection(population, penalties, config.tournament_k, rng)

            child = crossover(parent_a, parent_b, config.crossover_rate, rng, dataset)
            mutate(child, dataset, config.mutation_rate, rng)
            repair_timetable(child, dataset, rng)

            new_population.append(child)

        population = new_population

        # Evaluate new generation
        breakdowns = [evaluate(ind, dataset, config) for ind in population]
        penalties = [b.penalty for b in breakdowns]

        gen_best_idx = min(range(len(population)), key=lambda i: penalties[i])
        gen_best_breakdown = breakdowns[gen_best_idx]
        avg_penalty = sum(penalties) / len(penalties)

        if gen_best_breakdown.penalty < current_best_breakdown.penalty:
            current_best_ind = copy.deepcopy(population[gen_best_idx])
            current_best_breakdown = copy.deepcopy(gen_best_breakdown)

        history.append({
            "generation": gen,
            "best_penalty": current_best_breakdown.penalty,
            "avg_penalty": round(avg_penalty, 2),
            "best_hard": current_best_breakdown.hard_total,
            "best_soft": current_best_breakdown.soft_weighted,
        })

        if callback:
            callback(gen, current_best_breakdown, avg_penalty)

        # Early termination check: feasible and penalty sufficiently minimized
        if current_best_breakdown.hard_total == 0 and current_best_breakdown.penalty <= config.termination_penalty_threshold:
            stop_reason = f"Feasible timetable found at generation {gen} (Hard clashes: 0, Penalty: {current_best_breakdown.penalty})"
            break

    # Independent validation check
    val_report = validate(current_best_ind, dataset)
    status = "SUCCESS" if val_report.is_valid else "FAILED"

    return GAResult(
        dataset_name=getattr(dataset, "name", "College Dataset"),
        status=status,
        generations_run=len(history),
        stop_reason=stop_reason,
        initial_best=initial_best,
        final_best=current_best_ind,
        initial_breakdown=initial_breakdown,
        final_breakdown=current_best_breakdown,
        validation_report=val_report,
        history=history,
    )

